"""Regenerate the DXC bindings in src/portacom_dxc/_bindings from Windows.Win32.winmd.

python dxc/generate.py path/to/Windows.Win32.winmd
"""

import os
import shutil
import sys

import winmd2py

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "src", "portacom_dxc", "_bindings")

if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    shutil.rmtree(OUT, ignore_errors=True)
    winmd2py.generate(sys.argv[1], OUT, ["Windows.Win32.Graphics.Direct3D.Dxc"])
    with open(os.path.join(OUT, "__init__.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(
            f"# Generated by winmd2py from {os.path.basename(sys.argv[1])} (Microsoft.Windows.SDK.Win32Metadata,\n"
            "# MIT License, Copyright (c) Microsoft Corporation). Regenerate with dxc/generate.py.\n"
        )
