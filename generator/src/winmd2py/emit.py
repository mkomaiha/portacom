"""Python source for the bindings of one or more namespaces of a .winmd file.

Every namespace becomes a package (<namespace as directories>/__init__.py)
under the output directory, which is a package too, so a namespace and the
namespaces below it can both have bindings.  Types that the requested
namespaces use from other namespaces, of the same file or of a reference file
(--ref), are generated into partial modules for those namespaces, so the
output is self-contained.

A generated module declares, in order: the typedefs it uses, enums,
constants, struct classes, interface classes, coclasses, struct layouts,
method signatures, delegates (function pointer types, with their
signatures) and functions.  Layouts and signatures refer to other modules
lazily, so modules import in any order.

The output directory's own __init__.py is written once, as a template for
the package's portacom.use_abi() call, and is never overwritten.

What the metadata declares once per architecture (a struct's fields or
packing, an enum's values, a function's signature) is declared once, and
chosen on import by portacom.ARCH (codegen.by_arch).

The output does not depend on the ABI the library was built with: each module
gets its portacom.Abi from abi_for() when it is imported, and routes named
typedefs, BSTR, VARIANT and SAFEARRAY through it.
"""

from __future__ import annotations

import keyword
import os
import re
import sys

from . import __version__
from .model import KNOWN_TYPEDEFS, PD_IN, PD_OPTIONAL, PD_OUT, Unsupported, WinMD, arch_names

HEADER = """\
# Generated by winmd2py {version} from {source}{partial}. Do not edit.
import ctypes as _c

import portacom as _rt
from portacom import codegen as _cg
from portacom.codegen import Param as _P

_NS = {namespace!r}
_abi = _cg.abi_for(_NS, __name__)
"""

# The output package's own __init__.py, written once
PACKAGE_INIT = '''\
"""{package}: bindings generated by winmd2py from {source}.

This file is yours: winmd2py writes it once and never overwrites it. Bindings
for a library built for Linux or macOS declare here how it differs from the
Windows ABI, before any submodule is imported (see portacom.use_abi):
"""

# import ctypes
# import portacom
#
# portacom.use_abi(__name__, portacom.Abi("mylib", library="MyLib.dll", typedefs={{"BOOL": ctypes.c_long}}))
'''

RESERVED = set(keyword.kwlist) | {"self", "_c", "_rt", "_cg", "_P", "_NS", "_abi"}
ENUM_RESERVED = set(keyword.kwlist) | {"name", "value", "mro"}
ALL_ARCHES = arch_names(None)

# A typedef default that is safe to evaluate on import: it refers to no module's types
_HOISTABLE = re.compile(r"(_cg\.Ptr\()*(_c\.\w+|None|_rt\.GUID|_abi\.\w+)\)*")


def pyname(name: str) -> str:
    """name, or name_ where it is a Python keyword or used by the generated code."""
    return name + "_" if keyword.iskeyword(name) or name in RESERVED else name


def _enum_name(name):
    member = name.lstrip("_")  # Enum rejects _sunder_ names, and a class body mangles __names
    if not member[:1].isidentifier():
        member = "m_" + member
    return member + "_" if member in ENUM_RESERVED else member


def enum_members(names):
    """Python member names for an enum's C member names, and the C names that
    clashed.  Leading underscores are dropped; a keyword or a name Enum uses
    gets a trailing _; a name that would then clash with another member gets
    m_ in front."""
    kept = {name for name in names if _enum_name(name) == name}
    used, members, clashes = set(), [], []
    for name in names:
        member = _enum_name(name)
        if member != name and (member in kept or member in used):
            clashes.append(name)
            while member in kept or member in used:
                member = "m_" + member
        used.add(member)
        members.append(member)
    return members, clashes


def enum_source(cls, flags, underlying, values, scoped):
    """(source, clashing names) of an enum class with values [(C name, value)].
    An unscoped enum's members are also module globals under their C names,
    as C has them."""
    members, clashes = enum_members([name for name, _ in values])
    lines = [f"class {cls}({'_cg.Flags' if flags else '_cg.Enum'}):"]
    lines += [f"    {member} = {value!r}" for member, (_, value) in zip(members, values, strict=True)]
    if not values:
        lines.append("    pass")
    lines.append(f"\n\n{cls}._ctype_ = _c.{underlying}")
    if not scoped:
        lines += [
            f"{name} = {cls}.{member}"
            for (name, _), member in zip(values, members, strict=True)
            if pyname(name) == name
        ]
    return "\n".join(lines), clashes


def builtin(namespace: str, name: str) -> str | None:
    """The runtime type that stands for a well-known metadata type, if any."""
    if name == "Guid" and namespace in ("System", "Windows.Win32.Foundation", ""):
        return "_rt.GUID"
    if name == "IUnknown":
        return "_rt.IUnknown"
    if name == "VARIANT" and namespace in (
        "Windows.Win32.System.Variant",
        "Windows.Win32.System.Com",
        "Windows.Win32.System.Ole",
        "",
    ):
        return "_abi.VARIANT"  # its BSTRs and arrays allocate the way the library does
    if name == "SAFEARRAY" and namespace in ("Windows.Win32.System.Com", "Windows.Win32.System.Ole", ""):
        return "_abi.SAFEARRAY"  # allocated the way the library's ABI does
    if name in ("IDispatch", "DISPPARAMS", "EXCEPINFO") and namespace in ("Windows.Win32.System.Com", ""):
        return f"_rt.{name}"  # runtime-owned, so automation works without generated bindings
    if name == "IEnumVARIANT" and namespace in ("Windows.Win32.System.Ole", "Windows.Win32.System.Com", ""):
        return "_rt.IEnumVARIANT"
    return None


def _module_variable(namespace: str) -> str:
    return "_ns_" + namespace.replace(".", "_")


def arch_variants(items):
    """[(architectures, value)] -> [(by_arch key, value)], with architectures
    that share a value under one key ("x64_arm64").  [(None, value)] when one
    value serves every architecture; [] when there is none.  A value of None
    is no value, and of two values for one architecture the first wins."""
    by_arch = {}
    for arches, value in items:
        for arch in arches:
            if value is not None:
                by_arch.setdefault(arch, value)
    values = {}
    for arch in ALL_ARCHES:
        if arch in by_arch:
            values.setdefault(by_arch[arch], []).append(arch)
    if len(values) == 1 and len(by_arch) == len(ALL_ARCHES):
        return [(None, next(iter(values)))]
    return [("_".join(arches), value) for value, arches in values.items()]


class Generator:
    def __init__(self, winmd_path, namespaces=None, version=__version__, refs=()):
        self.winmd = WinMD(winmd_path, refs)
        self.source = self.winmd.name
        self.version = version
        available = self.winmd.namespaces()
        namespaces = list(namespaces or available)
        missing = [ns for ns in namespaces if ns not in available]
        if missing:
            raise ValueError(f"no namespace {', '.join(missing)} in {self.source}")
        self.requested = set(namespaces)
        self.notes = []  # what was left out or simplified, and why
        self._noted = set()
        self.modules = {}  # namespace -> sorted TypeDef indexes to declare
        self.sources = {}  # namespace -> names of the files its types come from
        self.aliases = {}  # namespace -> [(name, runtime type)] for builtin types declared there
        self._base_problems = {}
        self._where = ""  # what is being generated, for notes
        self._used_modules = set()  # per module: other namespaces it refers to
        self._typedefs = {}  # per module: typedef expression -> module variable
        self._delegate_problems = {}  # first variant's index -> why its signature is unsupported, or None
        self._probing = False
        self._collect()

    def note(self, text):
        if not self._probing and text not in self._noted:
            self._noted.add(text)
            self.notes.append(text)

    # -- what to generate -----------------------------------------------------------------

    def _collect(self):
        """The requested namespaces, and every type they use from the same file
        or a reference file."""
        w = self.winmd
        queue = [i for (ns, _), indexes in sorted(w.by_name.items()) if ns in self.requested for i in indexes]
        seen = set()
        while queue:
            index = queue.pop()
            if index in seen:
                continue
            seen.add(index)
            e = w.entity(index)
            if e.kind in ("attribute", "other"):
                continue
            runtime_type = builtin(e.namespace, e.name)
            if runtime_type and e.kind != "apis":
                if e.namespace in self.requested:
                    self.aliases.setdefault(e.namespace, []).append((e.name, runtime_type))
                    self.modules.setdefault(e.namespace, [])
                    self.sources.setdefault(e.namespace, set()).add(e.winmd.name)
                continue
            self.modules.setdefault(e.namespace, []).append(index)
            self.sources.setdefault(e.namespace, set()).add(e.winmd.name)
            queue += [d for d in self._dependencies(e) if d not in seen]
        for indexes in self.modules.values():
            indexes.sort()

    def _dependencies(self, e):
        w = self.winmd
        trees = []
        try:
            if e.kind == "interface":
                base = w.interface_base(e)
                if base:
                    trees.append(("ref", base))
                for m in w.methods(e):
                    trees += [m.ret] + [p.type for p in m.params]
            elif e.kind in ("struct", "union"):
                trees += [t for _, t, _ in w.fields(e)]
                trees += [("ref", ("def", child)) for child in w.nested_of(e)]
            elif e.kind == "typedef":
                trees.append(w.typedef_target(e))
            elif e.kind == "delegate":
                m = w.invoke(e)
                trees += [m.ret] + [p.type for p in m.params]
            elif e.kind == "apis":
                for m, _, _ in w.apis_members(e)[0]:
                    trees += [m.ret] + [p.type for p in m.params]
        except Unsupported:
            pass
        deps = []
        for t in trees:
            while t[0] in ("ptr", "array"):
                t = t[1]
            if t[0] == "ref" and t[1][0] == "def":
                deps += w.variants(w.entity(t[1][1]))
        return deps

    # -- type expressions -----------------------------------------------------------------

    def expr(self, t, ns, context="param"):
        """The Python expression for a type tree, used from namespace ns.

        In struct fields (context "field"), pointers to interfaces and to other
        namespaces' structs are plain void*, so that laying out a struct does not
        import other modules for them."""
        kind = t[0]
        if kind == "prim":
            return "_c." + t[1]
        if kind == "void":
            return "None"
        if kind == "unsupported":
            raise Unsupported(t[1])
        if kind == "array":
            return f"_cg.Array({self.expr(t[1], ns, context)}, {t[2]})"
        if kind == "ref":
            return self.ref(t[1], ns, context)
        if kind != "ptr":
            raise Unsupported(f"type {t!r}")

        target = t[1]
        if target[0] == "unsupported":
            return "_cg.Ptr(None)"
        if target[0] == "ref":
            key = target[1]
            if context != "field" and self.winmd.is_interface_key(key):
                try:
                    return self.ref(key, ns, context)  # IFoo* is written as the class IFoo
                except Unsupported:
                    return "_rt.IUnknown"
            target_ns, name = self.winmd.key_name(key)
            if key[0] == "ext" and not builtin(target_ns, name) and name not in KNOWN_TYPEDEFS:
                return "_cg.Ptr(None)"  # a pointer to something unknown is still a pointer
            if context == "field" and key[0] == "def":
                e = self.winmd.entity(key[1])
                if e.kind == "interface" or (e.namespace != ns and e.kind in ("struct", "union")):
                    return "_cg.Ptr(None)"
        return f"_cg.Ptr({self.expr(target, ns, context)})"

    def ref(self, key, ns, context):
        w = self.winmd
        ref_ns, name = w.key_name(key)
        runtime_type = builtin(ref_ns, name)
        if runtime_type:
            return runtime_type
        if key[0] == "ext":
            if name in KNOWN_TYPEDEFS:
                return self.typedef(name, f"_c.{KNOWN_TYPEDEFS[name]}")
            raise Unsupported(w.missing(ref_ns, name))
        e = w.entity(key[1])
        if e.kind == "typedef":
            default = KNOWN_TYPEDEFS.get(e.name)
            default = f"_c.{default}" if default else self.expr(w.typedef_target(e), ns, "field")
            return self.typedef(e.name, default)
        if e.kind == "delegate":
            problem = self._delegate_problem(e)
            if problem:
                self.note(f"{self._where}: delegate {e.name} passed as void*, {problem}")
                return "_c.c_void_p"
        if e.kind in ("coclass", "apis", "attribute", "other"):
            raise Unsupported(f"{e.name} is not a type")
        if context == "field" and e.kind == "interface":
            return "_c.c_void_p"
        if e.namespace == ns:
            return e.pyname
        self._used_modules.add(e.namespace)
        return f"{_module_variable(e.namespace)}.{e.pyname}"

    def _delegate_problem(self, e):
        """Why a delegate's signature (of any of its variants) cannot be
        described, or None.  Worked out without touching the module being
        generated."""
        w = self.winmd
        variants = w.variants(e)
        if variants[0] not in self._delegate_problems:
            self._delegate_problems[variants[0]] = None  # a delegate that takes itself
            saved = self._used_modules, self._typedefs, self._where, self._probing
            self._used_modules, self._typedefs, self._probing = set(), {}, True
            problem = None
            try:
                for index in variants:
                    self.signature(w.invoke(w.entity(index)), e.namespace)
            except Unsupported as error:
                problem = str(error)
            finally:
                self._used_modules, self._typedefs, self._where, self._probing = saved
            self._delegate_problems[variants[0]] = problem
        return self._delegate_problems[variants[0]]

    def typedef(self, name, default):
        """A use of a named typedef: a module variable (_t_NAME) set once on import."""
        text = f"_abi.typedef({name!r}, {default})"
        if not _HOISTABLE.fullmatch(default):
            return text
        variable = self._typedefs.get(text)
        if variable is None:
            taken = set(self._typedefs.values())
            variable, n = f"_t_{name}", 2
            while variable in taken:
                variable, n = f"_t_{name}_{n}", n + 1
            self._typedefs[text] = variable
        return variable

    # -- signatures -------------------------------------------------------------------------

    def signature(self, m, ns):
        """'(restype, (Param, ...))' for a method or function."""
        restype = self.expr(m.ret, ns)
        if not m.params:
            return f"({restype}, ())"
        params = "".join(f"\n        {self.param(p, i, m.params, ns)}," for i, p in enumerate(m.params))
        return f"({restype}, ({params}\n    ))"

    def param(self, p, i, params, ns):
        is_out = bool(p.flags & PD_OUT)
        flags = []
        if p.flags & PD_IN or not is_out:
            flags.append("IN")
        if is_out:
            flags.append("OUT")
        for attribute, flag in (
            ("ReservedAttribute", "OPTIONAL"),
            ("RetValAttribute", "RETVAL"),
            ("ComOutPtrAttribute", "COMOUTPTR"),
            ("ConstAttribute", "CONST"),
        ):
            if attribute in p.attrs and flag not in flags:
                flags.append(flag)
        if p.flags & PD_OPTIONAL and "OPTIONAL" not in flags:
            flags.insert(2 if is_out else 1, "OPTIONAL")

        extra = ""
        info = p.attrs.get("NativeArrayInfoAttribute")
        if info is not None and p.type[0] == "ptr":
            index, const = info.get("CountParamIndex"), info.get("CountConst")
            if index is not None and 0 <= index < len(params):
                extra += f", count={index}"
            elif const is not None and const > 0:
                extra += f", size={const}"
        size = p.attrs.get("MemorySizeAttribute", {}).get("BytesParamIndex")
        if size is not None and 0 <= size < len(params):
            extra += f", bytes={size}"
        if is_out and p.type == ("ptr", ("ptr", ("void",))):
            iid = self.iid_param(i, params)
            if iid is not None:
                extra += f", iid={iid}"
        flag_text = " | ".join(f"_cg.{f}" for f in flags)
        return f"_P({pyname(p.name)!r}, {self.expr(p.type, ns)}, {flag_text}{extra})"

    def iid_param(self, out_index, params):
        """The REFIID parameter that says what a void** [out] parameter is."""
        best = None
        for j, q in enumerate(params):
            if j == out_index or q.type[0] != "ptr" or q.type[1][0] != "ref":
                continue
            _, name = self.winmd.key_name(q.type[1][1])
            if name == "Guid" and "iid" in q.name.lower():
                if best is None or (best < j < out_index) or best > out_index:
                    best = j
        return best

    # -- output ------------------------------------------------------------------------------

    def generate(self, outdir):
        """Write the modules, and return their paths."""
        package = os.path.basename(os.path.normpath(outdir))
        _write_if_missing(os.path.join(outdir, "__init__.py"), PACKAGE_INIT.format(package=package, source=self.source))
        written = []
        for ns in sorted(self.modules):
            parts = ns.split(".")
            for k in range(1, len(parts)):  # every directory on the way is a package
                _write_if_missing(os.path.join(outdir, *parts[:k], "__init__.py"), "")
            path = os.path.join(outdir, *parts, "__init__.py")
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(self.module(ns))
            written.append(path)
        return written

    def module(self, ns):
        """The source of one namespace's module."""
        self._used_modules = set()
        self._typedefs = {}  # typedef expression -> module variable
        kinds = self._by_kind(ns)
        structs = kinds.get("struct", []) + kinds.get("union", [])
        interfaces = self._interfaces_bases_first([group[0] for group in kinds.get("interface", [])])
        apis = [e for group in kinds.get("apis", []) for e in group] if ns in self.requested else []

        sections = [
            ["\n".join(f"{name} = {target}" for name, target in sorted(self.aliases.get(ns, [])))],
            [self.enum(group, ns) for group in kinds.get("enum", [])],
            self.constants(apis),
            [
                f"class {group[0].pyname}(_cg.{'Union' if group[0].kind == 'union' else 'Structure'}):\n    pass"
                for group in structs
            ],
            [self.interface(e, ns) for e in interfaces],
            [self.coclass(group[0]) for group in kinds.get("coclass", [])],
            [self.layout(group, ns) for group in structs],
            [self.signatures(e, ns) for e in interfaces],
            [self.delegate(group, ns) for group in kinds.get("delegate", [])],
            self.functions(apis, ns),
        ]
        if structs:
            sections.append(["_cg.finish_layouts(" + "".join(f"\n    {g[0].pyname}," for g in structs) + "\n)"])
        body = "\n\n\n".join(item for section in sections for item in section if item)

        partial = "" if ns in self.requested else " (partial: only the types other namespaces use)"
        source = ", ".join(sorted(self.sources.get(ns, ()))) or self.source
        header = HEADER.format(version=self.version, source=source, partial=partial, namespace=ns)
        lazy = "".join(
            f"{_module_variable(other)} = _cg.LazyModule(__name__, _NS, {other!r})\n"
            for other in sorted(self._used_modules)
        )
        typedefs = "".join(f"{variable} = {text}\n" for text, variable in self._typedefs.items())
        return header + lazy + typedefs + "\n\n" + body + "\n"

    def _by_kind(self, ns):
        """This module's TypeDefs by kind, with the structs, unions and enums
        nested in its structs (named Outer_Inner), as groups: the variants of
        one type by architecture."""
        w = self.winmd
        groups = {}

        def add(e):
            group = groups.setdefault(e.pyname, [])
            if e not in group:
                group.append(e)

        for index in self.modules[ns]:
            e = w.entity(index)
            add(e)
            for child in self._nested(e):
                if child.kind in ("struct", "union", "enum"):
                    add(child)
        kinds = {}
        for group in groups.values():
            kinds.setdefault(group[0].kind, []).append(group)
        return kinds

    def _nested(self, e):
        for child in self.winmd.nested_of(e):
            c = self.winmd.entity(child)
            yield c
            yield from self._nested(c)

    def _interfaces_bases_first(self, interfaces):
        w = self.winmd
        local = {e.index for e in interfaces}
        order, done = [], set()

        def visit(e):
            if e.index in done:
                return
            done.add(e.index)
            base = w.interface_base(e)
            if base and base[0] == "def" and base[1] in local:
                visit(w.entity(base[1]))
            order.append(e)

        for e in interfaces:
            visit(e)
        return order

    @staticmethod
    def _arches(e, group):
        return ALL_ARCHES if len(group) == 1 else arch_names(e.arch)

    # -- declarations -------------------------------------------------------------------------

    def enum(self, group, ns):
        w = self.winmd
        e = group[0]
        flags = e.has_attr("FlagsAttribute")
        scoped = e.has_attr("ScopedEnumAttribute")  # else C names its members globally
        variants = [(self._arches(v, group), *w.enum_values(v)) for v in group]
        if len({(underlying, tuple(values)) for _, underlying, values in variants}) == 1:
            text, clashes = enum_source(e.pyname, flags, variants[0][1], variants[0][2], scoped)
            for name in clashes:
                self.note(f"{ns}.{e.pyname}.{name}: clashes with another member once its leading _ goes; named m_")
            return text

        cls = e.pyname
        members = {}  # C name -> member name, in any variant
        bodies = []
        for arches, _, values in variants:
            names, clashes = enum_members([name for name, _ in values])
            for name in clashes:
                self.note(f"{ns}.{cls}.{name}: clashes with another member once its leading _ goes; named m_")
            members.update(zip((name for name, _ in values), names, strict=True))
            entries = "".join(f"            {m!r}: {v!r},\n" for m, (_, v) in zip(names, values, strict=True))
            bodies.append((arches, "{\n" + entries + "        }"))
        values = "".join(f"        {key}={body},\n" for key, body in arch_variants(bodies))
        underlying = arch_variants([(arches, f"_c.{u}") for arches, u, _ in variants])
        ctype = underlying[0][1] if len(underlying) == 1 else self._by_arch_inline(underlying) + " or _c.c_int32"
        lines = [
            f"{cls} = _cg.{'Flags' if flags else 'Enum'}(\n    {cls!r},\n    _cg.by_arch(\n{values}    ) or {{}},\n"
            f"    module=__name__,\n)",
            f"{cls}._ctype_ = {ctype}",
        ]
        if not scoped:
            renamed = {name: member for name, member in members.items() if name != member and pyname(name) == name}
            lines.append(f"globals().update({cls}.__members__)")
            if renamed:
                lines.append(
                    f"globals().update({{c: {cls}[m] for c, m in {renamed!r}.items() if m in {cls}.__members__}})"
                )
        return "\n".join(lines)

    @staticmethod
    def _by_arch_inline(variants):
        return "_cg.by_arch(" + ", ".join(f"{key}={value}" for key, value in variants) + ")"

    def constants(self, apis):
        lines = []
        for e in apis:
            for name, kind, value, _ in self.winmd.apis_members(e)[1]:
                lines.append(f"{pyname(name)} = " + (f"_rt.GUID({value!r})" if kind == "guid" else repr(value)))
        return ["\n".join(lines)] if lines else []

    def _base_problem(self, e):
        """Why an interface's vtable cannot be laid out (its base, or a base of
        its base, is not here), or None."""
        if e.index not in self._base_problems:
            w = self.winmd
            self._base_problems[e.index] = None
            key = w.interface_base(e)
            problem = None
            if key is not None:
                ns, name = w.key_name(key)
                if key[0] == "ext":
                    if builtin(ns, name) is None:
                        problem = w.missing(ns, name)
                elif w.entity(key[1]).kind != "interface":
                    problem = f"{ns}.{name} is not an interface"
                else:
                    problem = self._base_problem(w.entity(key[1]))
            self._base_problems[e.index] = problem
        return self._base_problems[e.index]

    def interface(self, e, ns):
        w = self.winmd
        base = "_rt.IUnknown"
        base_key = w.interface_base(e)
        if base_key is not None and (base_key[0] == "def" or builtin(*w.key_name(base_key))):
            base = self.ref(base_key, ns, "base")
        guid = e.guid or "00000000-0000-0000-0000-000000000000"
        methods = ", ".join(repr(name) for name in self._method_names(e))
        if methods and "," not in methods:
            methods += ","
        return (
            f"class {e.pyname}({base}):\n"
            f"    _iid_ = _rt.GUID({guid!r})\n"
            f"    _abi_ = _abi\n"
            f"    _methods_ = ({methods})\n\n\n"
            f"IID_{e.pyname} = {e.pyname}._iid_"
        )

    def _method_names(self, e):
        """Method names, with overloads numbered (Name, Name_2, ...)."""
        names, seen = [], {}
        for m in self.winmd.methods(e):
            seen[m.name] = seen.get(m.name, 0) + 1
            names.append(m.name if seen[m.name] == 1 else f"{m.name}_{seen[m.name]}")
        return names

    def coclass(self, e):
        return f"{e.pyname} = _rt.CoClass({e.name!r}, {e.guid!r})\nCLSID_{e.pyname} = {e.pyname}._clsid_"

    def delegate(self, group, ns):
        """A function pointer type: a class whose signature is its Invoke's."""
        w = self.winmd
        e = group[0]
        if self._delegate_problem(e):
            return ""  # void* where it is used
        specs, cdecls = [], []
        for v in group:
            arches = self._arches(v, group)
            self._where = f"{ns}.{e.pyname}"
            specs.append((arches, self.signature(w.invoke(v), ns)))
            cdecls.append((arches, "True" if w.is_cdecl(v) else None))
        text = f"class {e.pyname}(_cg.Delegate):\n    _abi_ = _abi\n"
        variants = arch_variants(cdecls)
        if variants:
            text += f"    _cdecl_ = {self._one_or_by_arch(variants)}\n"
        return f"{text}\n\n{e.pyname}._signature_ = lambda: {self._spec_by_arch(specs, e.pyname)}"

    def _one_or_by_arch(self, variants):
        return variants[0][1] if variants[0][0] is None else self._by_arch_inline(variants)

    @staticmethod
    def _spec_by_arch(specs, name):
        """A signature from [(architectures, signature)]."""
        variants = arch_variants(specs)
        if variants[0][0] is None:
            return variants[0][1]
        spec = "_cg.by_arch(\n"
        for key, value in variants:
            spec += f"    {key}=" + value.replace("\n", "\n    ") + ",\n"
        return spec + f") or _cg.not_on_arch({name!r})"

    def _fields(self, e, ns):
        """(field lines, anonymous field names) of one struct declaration."""
        w = self.winmd
        lines, anonymous = [], []
        for name, t, _ in w.fields(e):
            self._where = f"{ns}.{e.pyname}.{name}"
            lines.append(f"({pyname(name)!r}, {self.expr(t, ns, 'field')}),")
            # nested in this struct, or in another variant of it (a TypeRef finds the first variant's)
            if name.startswith("Anonymous") and t[0] == "ref" and t[1][0] == "def":
                enclosing = w.entity(t[1][1]).enclosing
                if enclosing is not None and w.entity(enclosing).pyname == e.pyname:
                    anonymous.append(pyname(name))
        return tuple(lines), tuple(anonymous)

    def layout(self, group, ns):
        w = self.winmd
        cls = group[0].pyname
        fields, packs, anonymous = [], [], []
        for e in group:
            arches = self._arches(e, group)
            try:
                lines, anon = self._fields(e, ns)
            except Unsupported as error:
                size = w.layout_of(e)[1]
                if size and len(group) == 1:  # the size is all the metadata says, and all that matters
                    self.note(f"{ns}.{cls}: {error}; laid out as {size} opaque bytes")
                    return f"_cg.layout({cls}, lambda: [('_opaque', _cg.Array(_c.c_ubyte, {size}))])  # {error}"
                message = f"{cls}: layout unknown, {error}"
                self.note(f"{ns}.{message}")
                return f"_cg.layout({cls}, _cg.missing({message!r}))"
            fields.append((arches, lines))
            pack = w.layout_of(e)[0]
            packs.append((arches, str(pack) if pack else None))
            anonymous.append((arches, repr(anon) if anon else None))

        variants = arch_variants(fields)
        if variants[0][0] is None:
            text = "lambda: [\n" + "".join(f"    {line}\n" for line in variants[0][1]) + "]"
        else:
            text = "_cg.by_arch(\n"
            for key, lines in variants:
                text += f"    {key}=lambda: [\n" + "".join(f"        {line}\n" for line in lines) + "    ],\n"
            text += ")"
        options = ", abi=_abi"
        for option, values in (("pack", packs), ("anonymous", anonymous)):
            variants = arch_variants(values)
            if variants:
                value = variants[0][1] if variants[0][0] is None else self._by_arch_inline(variants)
                options += f", {option}={value}"
        text = f"_cg.layout({cls}, {text}{options})"

        bits = {}  # field -> [(arches, bits)]
        for e in group:
            for name, _, field_index in w.fields(e):
                found = w.bitfields(e, field_index)
                bits.setdefault(name, []).append((self._arches(e, group), repr(found) if found else None))
        for name, values in bits.items():
            variants = arch_variants(values)
            if variants:
                value = variants[0][1] if variants[0][0] is None else self._by_arch_inline(variants) + " or ()"
                text += f"\n_cg.bitfields({cls}, {pyname(name)!r}, {value})"
        return text

    def signatures(self, e, ns):
        problem = self._base_problem(e)
        if problem:
            message = f"{e.pyname}: base interface unknown, {problem}"
            self.note(f"{ns}.{message}")
            return f"{e.pyname}._signatures_ = _cg.missing({message!r})"
        entries = []
        for name, m in zip(self._method_names(e), self.winmd.methods(e), strict=False):
            self._where = f"{ns}.{e.pyname}.{name}"
            try:
                spec = self.signature(m, ns)
            except Unsupported as error:
                self.note(f"{ns}.{e.pyname}.{m.name}: {error}")
                spec = f"_cg.Unsupported({str(error)!r})"
            entries.append(f"    # {name}\n    {spec},")
        if not entries:
            return f"{e.pyname}._signatures_ = lambda: ()"
        return f"{e.pyname}._signatures_ = lambda: (\n" + "\n".join(entries) + "\n)"

    def functions(self, apis, ns):
        result = []
        for e in apis:
            by_name = {}
            for m, implmap, arch in self.winmd.apis_members(e)[0]:
                by_name.setdefault(m.name, []).append((m, implmap, arch))
            for name, declarations in by_name.items():
                specs, cdecls = [], []
                for m, (flags, _, _), arch in declarations:
                    arches = arch_names(arch) if len(declarations) > 1 else ALL_ARCHES
                    self._where = f"{ns}.{name}"
                    try:
                        spec = self.signature(m, ns)
                    except Unsupported as error:
                        self.note(f"{ns}.{name}: {error}")
                        spec = f"_cg.Unsupported({str(error)!r})"
                    specs.append((arches, spec))
                    cdecls.append((arches, "True" if flags & 0x700 == 0x200 else None))
                _, (_, import_name, library), _ = declarations[0]
                spec = self._spec_by_arch(specs, name)
                cdecl = ""
                variants = arch_variants(cdecls)
                if variants:
                    cdecl = f", cdecl={self._one_or_by_arch(variants)}"
                result.append(
                    f"{pyname(name)} = _cg.Function(_abi, {library!r}, {import_name or name!r}, lambda: {spec}{cdecl})"
                )
        return ["\n\n".join(result)] if result else []


def generate(winmd, outdir, namespaces=None, refs=(), quiet=False):
    """Write bindings for the namespaces of a .winmd file (default: all of them)
    as the package directory outdir, and return the paths written.

    refs are .winmd files whose types it uses (Microsoft.Direct3D.D3D12.winmd
    uses Windows.Win32.winmd's); what it uses from them is generated too.
    Unless quiet, what was left out or simplified is printed to stderr.
    """
    generator = Generator(winmd, namespaces, refs=refs)
    written = generator.generate(outdir)
    if not quiet:
        for note in generator.notes:
            print(f"winmd2py: {note}", file=sys.stderr)
    return written


def _write_if_missing(path, text):
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
