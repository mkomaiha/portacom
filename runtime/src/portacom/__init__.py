"""portacom: classic COM from Python, through ctypes, on Windows, Linux and macOS.

Bindings generated by winmd2py import this runtime.  Using them:

    import ctypes, portacom
    import my_bindings.My.Namespace as api

    obj = api.CreateThing(api.CLSID_Thing, api.IThing)   # riid/ppv: pass the class
    value = obj.GetValue()                               # [out] arguments are returned
    other = obj.query(api.IOther)                        # None if not implemented

    class Callback(portacom.ComObject):                  # implementing an interface
        _interfaces_ = (api.ICallback,)

        def Notify(self, message):
            print(message)

Errors raise portacom.COMError.

A .winmd describes the Windows ABI.  Where a library built for Linux or macOS
differs (BOOL or LONG width, BSTR allocation), declare it in the bindings'
__init__.py, before their modules are imported (Windows keeps the metadata's):

    portacom.use_abi(__name__, portacom.Abi("mylib", library="mylib.dll", typedefs={"BOOL": ctypes.c_long}))
"""

